#include "../includes/libft.h"

void	ft_skip_space(const char *str, int *i)
{
	while ((str[*i] == ' ' || str[*i] == '\t') || (str[*i] == '\r'
			|| str[*i] == '\v' || str[*i] == '\f'))
		(*i)++;
}
