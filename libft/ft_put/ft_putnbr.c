#include "../includes/libft.h"

void	ft_putnbr(int n)
{
	long	nbr;
	char	c;

	nbr = n;
	if (nbr < 0)
	{
		write(1, "-", 1);
		nbr = -nbr;
	}
	if (nbr / 10 > 0)
		ft_putnbr(nbr / 10);
	c = n % 10 + '0';
	write(1, &c, 1);
}
